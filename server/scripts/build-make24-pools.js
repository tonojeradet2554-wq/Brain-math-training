// Regenerates src/games/make24-pools.js from the solver. Run: npm run pools --workspace server
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

// Bootstrap: make24.js imports the pools file, so make sure one exists first.
const target = fileURLToPath(new URL('../src/games/make24-pools.js', import.meta.url));
if (!fs.existsSync(target)) fs.writeFileSync(target, 'export const MAKE24_POOLS = { easy: [], normal: [], hard: [] };\n');

const { computePools } = await import('../src/games/make24.js');
const pools = computePools();
const body = Object.entries(pools)
  .map(([level, sets]) => `  ${level}: [\n${sets.map((s) => `    [${s.join(', ')}],`).join('\n')}\n  ],`)
  .join('\n');

fs.writeFileSync(
  target,
  `// GENERATED by scripts/build-make24-pools.js — do not edit by hand.\n` +
    `// Every 4-number set (1–13) that can make 24, grouped by difficulty.\n` +
    `export const MAKE24_POOLS = {\n${body}\n};\n`,
);
console.log('make24-pools.js:', Object.fromEntries(Object.entries(pools).map(([k, v]) => [k, v.length])));
